/**
 * Run the built script with a fake plugin API and return the test hook.
 */
function mountPanel(hostCall?: (name: string, input: Record<string, unknown>) => Promise<unknown>) {
  const html = buildPanelHtml()
  const { byId, document } = makeDom(html)
  const orca = {
    plugin: { request: () => new Promise(() => {}), on() {} },
    host: { has: () => false, ...(hostCall ? { call: hostCall } : {}) },
    on() {}
  }
  const sandbox = vm.createContext({ document, navigator: {}, orca, setInterval: () => 0 })
  vm.runInContext('globalThis.window = globalThis', sandbox)
  vm.runInContext(scriptOf(html), sandbox)
  const hook = (sandbox as { __presencePanel?: { render(s: unknown): void } }).__presencePanel
  return { byId, hook, sandbox }
}

test('full view renders timeline cells', () => {
  const { byId, hook, sandbox } = mountPanel()
  expect(hook).toBeDefined()
  // Why: tests only; the hook must not be enumerable on window.
  expect(Object.keys(sandbox).includes('__presencePanel')).toBe(false)
  const timeline: Array<string | null> = Array.from({ length: 30 }, (_, i) =>
    i < 3 ? null : (['working', 'waiting', 'blocked', 'idle'] as const)[i % 4]
  )
  hook?.render(fullSnapshot(timeline))
  const cells = byId.get('strip')?.children ?? []
  expect(cells.length).toBe(30)
  cells.forEach((cell, i) => {
    expect(cell.getAttribute('data-state')).toBe(timeline[i] ?? 'none')
  })
  // A shorter or missing timeline still renders 30 "no data" cells.
  hook?.render(fullSnapshot([]))
  expect(byId.get('strip')?.children.length).toBe(30)
  expect(byId.get('strip')?.children.every((c) => c.getAttribute('data-state') === 'none')).toBe(true)
})

