/**
 * Minimal DOM element: attributes, children, class list, style bag. Only the
 * calls `src/panel/panel.js` makes are implemented.
 */
class FakeElement {
  id = ''
  textContent = ''
  className = ''
  hidden = false
  checked = false
  disabled = false
  src = ''
  scrollTop = 0
  clientHeight = 0
  scrollHeight = 0
  style: Record<string, string> = {}
  children: FakeElement[] = []
  attrs = new Map<string, string>()
  classList = {
    add: (name: string) => {
      const set = new Set(this.className.split(/\s+/).filter(Boolean))
      set.add(name)
      this.className = [...set].join(' ')
    },
    remove: (name: string) => {
      this.className = this.className.split(/\s+/).filter((n) => n && n !== name).join(' ')
    },
    toggle: (name: string, on?: boolean) => {
      const has = this.className.split(/\s+/).includes(name)
      if (on === undefined ? !has : on) this.classList.add(name)
      else this.classList.remove(name)
    }
  }
  listeners = new Map<string, Array<() => void>>()
  addEventListener(type: string, fn: () => void) {
    this.listeners.set(type, [...(this.listeners.get(type) ?? []), fn])
  }
  dispatch(type: string) {
    for (const fn of this.listeners.get(type) ?? []) fn()
  }
  setAttribute(name: string, value: string) {
    this.attrs.set(name, String(value))
  }
  getAttribute(name: string) {
    return this.attrs.get(name) ?? null
  }
  appendChild(child: FakeElement) {
    this.children.push(child)
    return child
  }
  removeChild(child: FakeElement) {
    this.children = this.children.filter((c) => c !== child)
    return child
  }
  get firstChild() {
    return this.children[0] ?? null
  }
}

/**
 * Document shim whose element registry mirrors every `id="…"` in the built
 * HTML, so a missing id in `panel.html` fails the test, not the real frame.
 */
function makeDom(html: string) {
  const byId = new Map<string, FakeElement>()
  for (const match of html.matchAll(/\sid="([^"]+)"/g)) {
    const el = new FakeElement()
    el.id = match[1]
    byId.set(match[1], el)
  }
  const document = {
    getElementById: (id: string) => byId.get(id) ?? null,
    createElement: () => new FakeElement(),
    createTextNode: (text: string) => Object.assign(new FakeElement(), { textContent: text }),
    querySelectorAll: () => [],
    documentElement: new FakeElement()
  }
  return { byId, document }
}

function scriptOf(html: string): string {
  return html.match(/<script>([\s\S]*?)<\/script>/)?.[1] ?? ''
}

test('panel/index.html is up to date', () => {
  expect(readFileSync(join(root, 'panel/index.html'), 'utf8')).toBe(buildPanelHtml())
})

test('built panel has no network or script src', () => {
  const html = buildPanelHtml()
  expect(html.startsWith('<!-- Generated by scripts/build-panel.ts. Edit src/panel/ instead. -->')).toBe(true)
  expect(html.includes('/* PANEL_STYLES */')).toBe(false)
  expect(html.includes('/* PANEL_SCRIPT */')).toBe(false)
  expect(/<script[^>]*\ssrc=/.test(html)).toBe(false)
  expect(/<link[^>]*\shref=/.test(html)).toBe(false)
  expect(html.includes('http')).toBe(false)
  expect(html.includes('orca-panel-action')).toBe(false)
  expect(html.includes('window.orca')).toBe(true)
  expect(html.includes('plugin.request')).toBe(true)
  expect(html.includes('presence.run')).toBe(true)
  expect(html.includes('Open this panel in the Orca desktop app to see live status.')).toBe(true)
  expect(html.includes('--orca-background')).toBe(true)
  expect(html.includes('../assets/state-')).toBe(true)
})

test('built panel script runs against a frozen window.orca', () => {
  const html = buildPanelHtml()
  // Why: window.orca is a read-only global in the frame. Running the inline
  // script as a classic script against such a global catches a top-level
  // `var orca`, which assigns window.orca and throws in strict mode.
  const { byId, document } = makeDom(html)
  const sandbox = vm.createContext({ document, navigator: {} })
  vm.runInContext(
    'Object.defineProperty(globalThis, "orca", { value: Object.freeze({}), writable: false }); globalThis.window = globalThis',
    sandbox
  )
  expect(() => vm.runInContext(scriptOf(html), sandbox)).not.toThrow()
  // Browser client (no plugin API): the static note shows, the app hides.
  expect(byId.get('static-note')?.className.includes('hidden')).toBe(false)
  expect(byId.get('app')?.className.includes('hidden')).toBe(true)
})

